-- Fee Collection & Management (School/College)
-- Import via phpMyAdmin or: mysql -u root -P 3306 < schema.sql
-- Creates the database, schema, and demo seed data.

CREATE DATABASE IF NOT EXISTS fee_collection_management
    CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE fee_collection_management;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS payment_allocations;
DROP TABLE IF EXISTS payments;
DROP TABLE IF EXISTS student_dues;
DROP TABLE IF EXISTS fee_structure_items;
DROP TABLE IF EXISTS fee_structures;
DROP TABLE IF EXISTS fee_heads;
DROP TABLE IF EXISTS students;
DROP TABLE IF EXISTS classes;
DROP TABLE IF EXISTS users;
SET FOREIGN_KEY_CHECKS = 1;

-- ============================================================
-- Schema
-- ============================================================

CREATE TABLE users (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL UNIQUE,
    password      VARCHAR(255) NOT NULL,
    role          ENUM('super_admin','accountant','student') NOT NULL,
    status        ENUM('active','inactive') NOT NULL DEFAULT 'active',
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE classes (
    id             INT AUTO_INCREMENT PRIMARY KEY,
    name           VARCHAR(50) NOT NULL,
    section        VARCHAR(10) NOT NULL,
    academic_year  VARCHAR(9) NOT NULL,
    created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_class (name, section, academic_year)
) ENGINE=InnoDB;

CREATE TABLE students (
    id               INT AUTO_INCREMENT PRIMARY KEY,
    user_id          INT NOT NULL UNIQUE,
    admission_no     VARCHAR(30) NOT NULL UNIQUE,
    class_id         INT NOT NULL,
    roll_no          INT NOT NULL DEFAULT 0,
    guardian_name    VARCHAR(100) NULL,
    guardian_phone   VARCHAR(20) NULL,
    dob              DATE NULL,
    address          VARCHAR(255) NULL,
    status           ENUM('active','inactive') NOT NULL DEFAULT 'active',
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (class_id) REFERENCES classes(id) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE fee_heads (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    name          VARCHAR(100) NOT NULL UNIQUE,
    description   VARCHAR(255) NULL,
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE fee_structures (
    id                INT AUTO_INCREMENT PRIMARY KEY,
    class_id          INT NOT NULL,
    term              VARCHAR(30) NOT NULL,
    academic_year     VARCHAR(9) NOT NULL,
    due_date          DATE NOT NULL,
    late_fee_type     ENUM('flat','percent') NOT NULL DEFAULT 'flat',
    late_fee_value    DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    grace_days        INT NOT NULL DEFAULT 0,
    created_by        INT NULL,
    status            ENUM('active','inactive') NOT NULL DEFAULT 'active',
    created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_structure (class_id, term, academic_year),
    FOREIGN KEY (class_id) REFERENCES classes(id) ON DELETE CASCADE,
    FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE fee_structure_items (
    id                 INT AUTO_INCREMENT PRIMARY KEY,
    fee_structure_id   INT NOT NULL,
    fee_head_id        INT NOT NULL,
    amount             DECIMAL(10,2) NOT NULL,
    UNIQUE KEY uq_structure_item (fee_structure_id, fee_head_id),
    FOREIGN KEY (fee_structure_id) REFERENCES fee_structures(id) ON DELETE CASCADE,
    FOREIGN KEY (fee_head_id) REFERENCES fee_heads(id) ON DELETE RESTRICT
) ENGINE=InnoDB;

-- A student_dues row is generated automatically (by the app, not manually) for every
-- student against every fee_structure_item that applies to their class. It is the
-- materialized "what this student owes for this fee head, this term" record that
-- payments, concessions and late fees are all tracked against.
CREATE TABLE student_dues (
    id                      INT AUTO_INCREMENT PRIMARY KEY,
    student_id              INT NOT NULL,
    fee_structure_item_id   INT NOT NULL,
    base_amount             DECIMAL(10,2) NOT NULL,
    concession_amount       DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    concession_reason       VARCHAR(255) NULL,
    concession_by           INT NULL,
    concession_at           DATETIME NULL,
    late_fee_amount         DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    late_fee_applied_at     DATETIME NULL,
    amount_paid             DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    due_date                DATE NOT NULL,
    status                  ENUM('pending','partial','paid') NOT NULL DEFAULT 'pending',
    created_at              TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_student_due (student_id, fee_structure_item_id),
    FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE,
    FOREIGN KEY (fee_structure_item_id) REFERENCES fee_structure_items(id) ON DELETE CASCADE,
    FOREIGN KEY (concession_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE payments (
    id             INT AUTO_INCREMENT PRIMARY KEY,
    student_id     INT NOT NULL,
    receipt_no     VARCHAR(30) NOT NULL UNIQUE,
    amount         DECIMAL(10,2) NOT NULL,
    method         ENUM('cash','cheque','online') NOT NULL DEFAULT 'cash',
    reference_no   VARCHAR(60) NULL,
    remarks        VARCHAR(255) NULL,
    recorded_by    INT NOT NULL,
    paid_at        DATETIME NOT NULL,
    created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE,
    FOREIGN KEY (recorded_by) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB;

-- One payment can be split across several dues (or several payments can chip away
-- at a single due over time) -- this join table is what makes partial payments work.
CREATE TABLE payment_allocations (
    id                INT AUTO_INCREMENT PRIMARY KEY,
    payment_id        INT NOT NULL,
    student_due_id    INT NOT NULL,
    allocated_amount  DECIMAL(10,2) NOT NULL,
    FOREIGN KEY (payment_id) REFERENCES payments(id) ON DELETE CASCADE,
    FOREIGN KEY (student_due_id) REFERENCES student_dues(id) ON DELETE CASCADE
) ENGINE=InnoDB;

